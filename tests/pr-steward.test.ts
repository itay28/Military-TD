type Fetch = (url: string, init: RequestInit) => Promise<Response>;
const ok = (body: unknown = {}) => new Response(JSON.stringify(body), { status: 200 });
const calls = (fetchFn: Mock<Fetch>) => fetchFn.mock.calls.map(([url, init]) => `${init.method} ${url}`);
const api = 'https://api.github.com/repos/itay28/Military-TD';
const settings: StewardSettings = {
  steward: { url: 'https://fire.example/steward', token: 'steward-token' },
  merge: true,
};
const fireOk = vi.fn<Fetch>(async (url: string) =>
  url.startsWith('https://fire.example') ? ok({ claude_code_session_url: 'https://claude.ai/code/session_1' }) : ok(),
);

describe('act', () => {
  const steward: Decision = {
    kind: 'steward',
    reasons: ['ci', 'review'],
    round: 2,
    retry: false,
    clearNeedsYou: false,
  };

  it('fires a steward round with the PR, reasons and round, then posts the round marker with the session link', async () => {
    fireOk.mockClear();
    await act(pr(), steward, 'gh-token', settings, fireOk);
    expect(calls(fireOk)).toEqual(['POST https://fire.example/steward', `POST ${api}/issues/7/comments`]);
    const { text } = JSON.parse(fireOk.mock.calls[0]![1].body as string) as { text: string };
    expect(text).toContain('PR: #7');
    expect(text).toContain('Reasons: ci, review');
    expect(text).toContain('Round: 2 of 3');
    const { body } = JSON.parse(fireOk.mock.calls[1]![1].body as string) as { body: string };
    expect(body).toContain(ROUND_MARKER);
    expect(body).toContain('https://claude.ai/code/session_1');
    expect(body).toContain(roundMeta(['ci', 'review'], 'base-1'));
  });

  it('removes needs-you when a maintainer comment restarted the PR', async () => {
    fireOk.mockClear();
    await act(pr(), { ...steward, clearNeedsYou: true }, 'gh-token', settings, fireOk);
    expect(calls(fireOk)).toContain(`DELETE ${api}/issues/7/labels/needs-you`);
  });

  it('says a retried round is a retry', async () => {
    fireOk.mockClear();
    await act(pr(), { ...steward, retry: true }, 'gh-token', settings, fireOk);
    const { body } = JSON.parse(fireOk.mock.calls[1]![1].body as string) as { body: string };
    expect(body).toMatch(/retry/i);
  });

  it.each([429, 500, 503])(
    'posts nothing and waits for the next run when the fire is refused with HTTP %i (#200)',
    async (status) => {
      const fetchFn = vi.fn<Fetch>(async () => new Response('busy', { status }));
      await expect(act(pr(), steward, 'gh-token', settings, fetchFn)).resolves.toBeUndefined();
      expect(calls(fetchFn)).toEqual(['POST https://fire.example/steward']);
    },
  );

  it('waits for the next run when the fire cannot reach the API', async () => {
    const fetchFn = vi.fn<Fetch>(async () => {
      throw new TypeError('fetch failed');
    });
    await expect(act(pr(), steward, 'gh-token', settings, fetchFn)).resolves.toBeUndefined();
  });

  it.each([401, 403, 404])('hands off loudly and throws when the fire is refused with HTTP %i', async (status) => {
    const fetchFn = vi.fn<Fetch>(async (url: string) =>
      url.startsWith('https://fire.example') ? new Response('denied', { status }) : ok(),
    );
    await expect(act(pr(), steward, 'gh-token', settings, fetchFn)).rejects.toThrow(/#7/);
    expect(calls(fetchFn)).toEqual([
      'POST https://fire.example/steward',
      `POST ${api}/issues/7/comments`,
      `POST ${api}/issues/7/labels`,
    ]);
    const { body } = JSON.parse(fetchFn.mock.calls[1]![1].body as string) as { body: string };
    expect(body).toContain(STUCK_MARKER);
    expect(body).toContain(`HTTP ${status}`);
    expect(body).toContain('ROUTINE_STEWARD_TOKEN');
  });

  it('says why when an unresolved conflict hands off', async () => {
    const fetchFn = vi.fn<Fetch>(async () => ok());
    await act(pr(), { kind: 'stuck', reasons: ['conflict'], conflict: true }, 'gh-token', settings, fetchFn);
    const { body } = JSON.parse(fetchFn.mock.calls[0]![1].body as string) as { body: string };
    expect(body).toContain("couldn't resolve the merge conflict");
  });

  it('hands off as stuck: needs-you label and a summary with the marker', async () => {
    const fetchFn = vi.fn<Fetch>(async () => ok());
    await act(pr(), { kind: 'stuck', reasons: ['ci'] }, 'gh-token', settings, fetchFn);
    // The summary comes first: the needs-you push (scripts/notify.ts) reads it when the label lands.
    expect(calls(fetchFn)).toEqual([`POST ${api}/issues/7/comments`, `POST ${api}/issues/7/labels`]);
    const { body } = JSON.parse(fetchFn.mock.calls[0]![1].body as string) as { body: string };
    expect(body).toContain(STUCK_MARKER);
  });

  it('updates the branch against the head it saw', async () => {
    const fetchFn = vi.fn<Fetch>(async () => ok());
    await act(pr(), { kind: 'update' }, 'gh-token', settings, fetchFn);
    expect(calls(fetchFn)).toEqual([`PUT ${api}/pulls/7/update-branch`]);
    expect(JSON.parse(fetchFn.mock.calls[0]![1].body as string)).toEqual({ expected_head_sha: 'abc123' });
  });

  it('squash-merges with the PR title and body, pinned to the head it checked', async () => {
    const fetchFn = vi.fn<Fetch>(async () => ok());
    await act(pr(), { kind: 'merge' }, 'gh-token', settings, fetchFn);
    expect(calls(fetchFn)).toEqual([`PUT ${api}/pulls/7/merge`]);
    expect(JSON.parse(fetchFn.mock.calls[0]![1].body as string)).toEqual({
      merge_method: 'squash',
      commit_title: 'feat: mortar tower (#7)',
      commit_message: 'Closes #3',
      sha: 'abc123',
    });
  });

  it('hands off when GitHub refuses the merge', async () => {
    const fetchFn = vi.fn<Fetch>(async (url: string) =>
      url.endsWith('/merge') ? new Response('{"message":"Review required"}', { status: 405 }) : ok(),
    );
    await act(pr(), { kind: 'merge' }, 'gh-token', settings, fetchFn);
    expect(calls(fetchFn)).toEqual([
      `PUT ${api}/pulls/7/merge`,
      `POST ${api}/issues/7/comments`,
      `POST ${api}/issues/7/labels`,
    ]);
    const { body } = JSON.parse(fetchFn.mock.calls[1]![1].body as string) as { body: string };
    expect(body).toContain('Review required');
  });

  it('leaves the PR for the next run when its head moved before the merge', async () => {
    const fetchFn = vi.fn<Fetch>(async () => new Response('{"message":"Head branch was modified"}', { status: 409 }));
    await act(pr(), { kind: 'merge' }, 'gh-token', settings, fetchFn);
    expect(calls(fetchFn)).toEqual([`PUT ${api}/pulls/7/merge`]);
  });

  it('only logs when its switch is off', async () => {
    const fetchFn = vi.fn<Fetch>(async () => ok());
    await act(pr(), steward, 'gh-token', { merge: false }, fetchFn);
    await act(pr(), { kind: 'update' }, 'gh-token', { merge: false }, fetchFn);
    await act(pr(), { kind: 'merge' }, 'gh-token', { merge: false }, fetchFn);
    expect(fetchFn).not.toHaveBeenCalled();
  });
});

describe('settingsFromEnv', () => {
  it('turns the steward on with AUTO_STEWARD and merging with AUTO_MERGE', () => {
    expect(settingsFromEnv({})).toEqual({ merge: false });
    expect(
      settingsFromEnv({ AUTO_STEWARD: 'on', AUTO_MERGE: 'on', ROUTINE_STEWARD_URL: 'u', ROUTINE_STEWARD_TOKEN: 't' }),
    ).toEqual({ steward: { url: 'u', token: 't' }, merge: true });
  });

  it('fails loudly when AUTO_STEWARD is on without its secrets', () => {
    expect(() => settingsFromEnv({ AUTO_STEWARD: 'on' })).toThrow(/ROUTINE_STEWARD_URL/);
  });
});
