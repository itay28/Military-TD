import { describe, expect, it, vi, type Mock } from 'vitest';
import {
  DONE_MARKER,
  REVIEW_HEADING,
  ROUND_MARKER,
  STUCK_MARKER,
  act,
  decide,
  settingsFromEnv,
  type Decision,
  type PrComment,
  type StewardPr,
  type StewardSettings,
} from '../scripts/pr-steward';

// The PR steward reconciles every open PR (#168): fire a steward round, merge the base, hand off, or merge.
const now = new Date('2026-10-26T12:00:00Z');
const at = (minutesAgo: number) => new Date(now.getTime() - minutesAgo * 60_000).toISOString();
const review = (minutesAgo: number): PrComment => ({
  author: 'claude',
  bot: true,
  association: 'NONE',
  body: `${REVIEW_HEADING}\n\nFindings…`,
  createdAt: at(minutesAgo),
});
const agent = (marker: string, minutesAgo: number): PrComment => ({
  author: 'itay28',
  bot: false,
  association: 'OWNER',
  body: `Round summary.\n${marker}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_`,
  createdAt: at(minutesAgo),
});
const action = (marker: string, minutesAgo: number): PrComment => ({ ...agent(marker, minutesAgo), body: marker });
const maintainer = (minutesAgo: number): PrComment => ({
  author: 'itay28',
  bot: false,
  association: 'OWNER',
  body: 'Please rename this.',
  createdAt: at(minutesAgo),
});

// A PR that is ready to merge: green, reviewed, and the review answered.
const pr = (over: Partial<StewardPr> = {}): StewardPr => ({
  number: 7,
  title: 'feat: mortar tower',
  body: 'Closes #3',
  isDraft: false,
  fork: false,
  base: 'main',
  head: 'feat/3-mortar',
  headSha: 'abc123',
  labels: [],
  mergeable: 'MERGEABLE',
  behind: false,
  checks: [
    { name: 'ci', state: 'success' },
    { name: 'e2e', state: 'success' },
    { name: 'claude-review', state: 'success' },
  ],
  unresolvedThreads: 0,
  comments: [review(60), agent(DONE_MARKER, 30)],
  ...over,
});
const kind = (p: StewardPr) => decide(p, now).kind;
const reasons = (p: StewardPr) => {
  const d = decide(p, now);
  return d.kind === 'steward' || d.kind === 'stuck' ? d.reasons : [];
};

describe('decide: skip', () => {
  it('skips drafts, forks and held PRs', () => {
    expect(kind(pr({ isDraft: true }))).toBe('skip');
    expect(kind(pr({ fork: true }))).toBe('skip');
    expect(kind(pr({ labels: ['hold'] }))).toBe('skip');
  });

  it('leaves release PRs to the maintainer: merging one publishes a release', () => {
    expect(decide(pr({ head: 'release-please--branches--main' }), now)).toMatchObject({
      kind: 'skip',
      why: expect.stringMatching(/release/),
    });
  });

  it('skips a handed-off PR until the maintainer comments', () => {
    const stuck = pr({ labels: ['needs-you'], comments: [review(90), action(STUCK_MARKER, 20)] });
    expect(kind(stuck)).toBe('skip');
    const answered = { ...stuck, comments: [...stuck.comments, maintainer(5)] };
    expect(decide(answered, now)).toMatchObject({
      kind: 'steward',
      reasons: ['review', 'comment'],
      clearNeedsYou: true,
    });
  });
});

describe('decide: wait', () => {
  it('waits while a relevant check runs, or the CI review is still running', () => {
    expect(kind(pr({ checks: [{ name: 'ci', state: 'pending' }] }))).toBe('wait');
    expect(
      kind(
        pr({
          checks: [
            { name: 'ci', state: 'success' },
            { name: 'claude-review', state: 'pending' },
          ],
        }),
      ),
    ).toBe('wait');
  });

  it('waits while GitHub is still computing mergeability', () => {
    expect(kind(pr({ mergeable: 'UNKNOWN' }))).toBe('wait');
  });

  it('waits while a round is in flight, and stops waiting once it is 3 hours old', () => {
    const red = { checks: [{ name: 'ci', state: 'failure' as const }] };
    expect(kind(pr({ ...red, comments: [action(ROUND_MARKER, 30)] }))).toBe('wait');
    expect(kind(pr({ ...red, comments: [action(ROUND_MARKER, 200)] }))).toBe('steward');
  });

  it('waits for the CI review before merging', () => {
    expect(decide(pr({ comments: [] }), now)).toMatchObject({ kind: 'wait', why: expect.stringMatching(/review/) });
  });
});

describe('decide: steward rounds', () => {
  it('fires for a conflict, even while checks run', () => {
    expect(reasons(pr({ mergeable: 'CONFLICTING', checks: [{ name: 'ci', state: 'pending' }] }))).toEqual(['conflict']);
  });

  it('fires for a failed check, but ignores bookkeeping checks', () => {
    expect(reasons(pr({ checks: [{ name: 'ci', state: 'failure' }] }))).toEqual(['ci']);
    const bookkeeping = ['board-sync', 'release-issue', 'claude-review'].map((name) => ({
      name,
      state: 'failure' as const,
    }));
    expect(kind(pr({ checks: [{ name: 'ci', state: 'success' }, ...bookkeeping] }))).toBe('merge');
  });

  it('fires for a CI review with no done marker after it', () => {
    expect(reasons(pr({ comments: [review(10)] }))).toEqual(['review']);
    expect(reasons(pr({ comments: [agent(DONE_MARKER, 30), review(10)] }))).toEqual(['review']);
  });

  it('fires for a maintainer comment after the last round, and for unresolved threads', () => {
    expect(reasons(pr({ comments: [review(60), agent(DONE_MARKER, 30), maintainer(5)] }))).toEqual(['comment']);
    expect(reasons(pr({ unresolvedThreads: 2 }))).toEqual(['threads']);
  });

  it('does not take agent or Action comments for maintainer comments', () => {
    const footer = { ...maintainer(5), body: 'Fixed.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' };
    expect(kind(pr({ comments: [review(60), agent(DONE_MARKER, 30), footer, action(ROUND_MARKER, 200)] }))).not.toBe(
      'steward',
    );
  });

  it('treats both footer wordings as agent comments', () => {
    const withFooter = {
      ...maintainer(5),
      body: 'Done.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    };
    expect(kind(pr({ comments: [review(60), agent(DONE_MARKER, 30), withFooter] }))).toBe('merge');
  });

  it('numbers the round, counting rounds since the latest maintainer comment', () => {
    const red = { checks: [{ name: 'ci', state: 'failure' as const }] };
    const done = (m: number) => [action(ROUND_MARKER, m + 5), agent(DONE_MARKER, m)];
    expect(decide(pr({ ...red, comments: [...done(300)] }), now)).toMatchObject({ kind: 'steward', round: 2 });
    expect(decide(pr({ ...red, comments: [...done(300), maintainer(250), ...done(200)] }), now)).toMatchObject({
      round: 2,
    });
  });

  it('hands off as stuck once 3 rounds were used', () => {
    const three = [400, 300, 200].flatMap((m) => [action(ROUND_MARKER, m + 5), agent(DONE_MARKER, m)]);
    expect(decide(pr({ checks: [{ name: 'ci', state: 'failure' }], comments: three }), now)).toEqual({
      kind: 'stuck',
      reasons: ['ci'],
    });
  });
});

describe('decide: update and merge', () => {
  it('merges the base itself when the PR is only behind', () => {
    expect(kind(pr({ behind: true }))).toBe('update');
  });

  it('merges a green PR whose review is answered and threads resolved', () => {
    expect(kind(pr())).toBe('merge');
  });

  it('leaves stacked PRs for after their parent merges', () => {
    expect(decide(pr({ base: 'feat/5-parent' }), now)).toMatchObject({
      kind: 'wait',
      why: expect.stringMatching(/stack/),
    });
  });
});

type Fetch = (url: string, init: RequestInit) => Promise<Response>;
const ok = (body: unknown = {}) => new Response(JSON.stringify(body), { status: 200 });
const calls = (fetchFn: Mock<Fetch>) => fetchFn.mock.calls.map(([url, init]) => `${init.method} ${url}`);
const api = 'https://api.github.com/repos/itay28/Military-TD';
const settings: StewardSettings = {
  steward: { url: 'https://fire.example/steward', token: 'steward-token' },
  merge: true,
};
const fireOk = vi.fn<Fetch>(async (url: string) =>
  url.startsWith('https://fire.example') ? ok({ claude_code_session_url: 'https://claude.ai/code/session_1' }) : ok(),
);

describe('act', () => {
  const steward: Decision = { kind: 'steward', reasons: ['ci', 'review'], round: 2, clearNeedsYou: false };

  it('fires a steward round with the PR, reasons and round, then posts the round marker with the session link', async () => {
    fireOk.mockClear();
    await act(pr(), steward, 'gh-token', settings, fireOk);
    expect(calls(fireOk)).toEqual(['POST https://fire.example/steward', `POST ${api}/issues/7/comments`]);
    const { text } = JSON.parse(fireOk.mock.calls[0]![1].body as string) as { text: string };
    expect(text).toContain('PR: #7');
    expect(text).toContain('Reasons: ci, review');
    expect(text).toContain('Round: 2 of 3');
    const { body } = JSON.parse(fireOk.mock.calls[1]![1].body as string) as { body: string };
    expect(body).toContain(ROUND_MARKER);
    expect(body).toContain('https://claude.ai/code/session_1');
  });

  it('removes needs-you when a maintainer comment restarted the PR', async () => {
    fireOk.mockClear();
    await act(pr(), { ...steward, clearNeedsYou: true }, 'gh-token', settings, fireOk);
    expect(calls(fireOk)).toContain(`DELETE ${api}/issues/7/labels/needs-you`);
  });

  it('posts no marker and throws when the fire fails', async () => {
    const fetchFn = vi.fn<Fetch>(async () => new Response('nope', { status: 500 }));
    await expect(act(pr(), steward, 'gh-token', settings, fetchFn)).rejects.toThrow(/#7/);
    expect(calls(fetchFn)).toEqual(['POST https://fire.example/steward']);
  });

  it('hands off as stuck: needs-you label and a summary with the marker', async () => {
    const fetchFn = vi.fn<Fetch>(async () => ok());
    await act(pr(), { kind: 'stuck', reasons: ['ci'] }, 'gh-token', settings, fetchFn);
    expect(calls(fetchFn)).toEqual([`POST ${api}/issues/7/labels`, `POST ${api}/issues/7/comments`]);
    const { body } = JSON.parse(fetchFn.mock.calls[1]![1].body as string) as { body: string };
    expect(body).toContain(STUCK_MARKER);
  });

  it('updates the branch against the head it saw', async () => {
    const fetchFn = vi.fn<Fetch>(async () => ok());
    await act(pr(), { kind: 'update' }, 'gh-token', settings, fetchFn);
    expect(calls(fetchFn)).toEqual([`PUT ${api}/pulls/7/update-branch`]);
    expect(JSON.parse(fetchFn.mock.calls[0]![1].body as string)).toEqual({ expected_head_sha: 'abc123' });
  });

  it('squash-merges with the PR title and body, pinned to the head it checked', async () => {
    const fetchFn = vi.fn<Fetch>(async () => ok());
    await act(pr(), { kind: 'merge' }, 'gh-token', settings, fetchFn);
    expect(calls(fetchFn)).toEqual([`PUT ${api}/pulls/7/merge`]);
    expect(JSON.parse(fetchFn.mock.calls[0]![1].body as string)).toEqual({
      merge_method: 'squash',
      commit_title: 'feat: mortar tower (#7)',
      commit_message: 'Closes #3',
      sha: 'abc123',
    });
  });

  it('hands off when GitHub refuses the merge', async () => {
    const fetchFn = vi.fn<Fetch>(async (url: string) =>
      url.endsWith('/merge') ? new Response('{"message":"Review required"}', { status: 405 }) : ok(),
    );
    await act(pr(), { kind: 'merge' }, 'gh-token', settings, fetchFn);
    expect(calls(fetchFn)).toEqual([
      `PUT ${api}/pulls/7/merge`,
      `POST ${api}/issues/7/labels`,
      `POST ${api}/issues/7/comments`,
    ]);
    const { body } = JSON.parse(fetchFn.mock.calls[2]![1].body as string) as { body: string };
    expect(body).toContain('Review required');
  });

  it('leaves the PR for the next run when its head moved before the merge', async () => {
    const fetchFn = vi.fn<Fetch>(async () => new Response('{"message":"Head branch was modified"}', { status: 409 }));
    await act(pr(), { kind: 'merge' }, 'gh-token', settings, fetchFn);
    expect(calls(fetchFn)).toEqual([`PUT ${api}/pulls/7/merge`]);
  });

  it('only logs when its switch is off', async () => {
    const fetchFn = vi.fn<Fetch>(async () => ok());
    await act(pr(), steward, 'gh-token', { merge: false }, fetchFn);
    await act(pr(), { kind: 'update' }, 'gh-token', { merge: false }, fetchFn);
    await act(pr(), { kind: 'merge' }, 'gh-token', { merge: false }, fetchFn);
    expect(fetchFn).not.toHaveBeenCalled();
  });
});

describe('settingsFromEnv', () => {
  it('turns the steward on with AUTO_STEWARD and merging with AUTO_MERGE', () => {
    expect(settingsFromEnv({})).toEqual({ merge: false });
    expect(
      settingsFromEnv({ AUTO_STEWARD: 'on', AUTO_MERGE: 'on', ROUTINE_STEWARD_URL: 'u', ROUTINE_STEWARD_TOKEN: 't' }),
    ).toEqual({ steward: { url: 'u', token: 't' }, merge: true });
  });

  it('fails loudly when AUTO_STEWARD is on without its secrets', () => {
    expect(() => settingsFromEnv({ AUTO_STEWARD: 'on' })).toThrow(/ROUTINE_STEWARD_URL/);
  });
});
